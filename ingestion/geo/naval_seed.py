def seed_naval_fleets(conn: psycopg.Connection) -> dict[str, int]:
    """Upsert strategic naval fleet positions keyed by code."""
    upserted = 0
    now = datetime.now(timezone.utc)
    with conn.cursor() as cur:
        for f in NAVAL_FLEETS:
            cur.execute(
                """
                INSERT INTO naval_fleets
                    (code, name, country_code, flag_country, fleet_type, flagship,
                     composition, operational_area, latitude, longitude, status,
                     threat_level, mission_brief, source_citation, last_reported_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT (code) DO UPDATE SET
                    name = EXCLUDED.name,
                    country_code = EXCLUDED.country_code,
                    flag_country = EXCLUDED.flag_country,
                    fleet_type = EXCLUDED.fleet_type,
                    flagship = EXCLUDED.flagship,
                    composition = EXCLUDED.composition,
                    operational_area = EXCLUDED.operational_area,
                    latitude = EXCLUDED.latitude,
                    longitude = EXCLUDED.longitude,
                    status = EXCLUDED.status,
                    threat_level = EXCLUDED.threat_level,
                    mission_brief = EXCLUDED.mission_brief,
                    source_citation = EXCLUDED.source_citation,
                    last_reported_at = EXCLUDED.last_reported_at
                """,
                (
                    f["code"],
                    f["name"],
                    f["country_code"],
                    f["flag_country"],
                    f["fleet_type"],
                    f["flagship"],
                    f.get("composition"),
                    f["operational_area"],
                    f["latitude"],
                    f["longitude"],
                    f.get("status", "deployed"),
                    f.get("threat_level", "routine"),
                    f.get("mission_brief"),
                    CITATION,
                    now,
                ),
            )
            upserted += 1

    logger.info("naval_fleets_seeded", extra={"count": upserted})
    return {"rows_upserted": upserted}


def run_naval_sync() -> dict[str, int]:
    """Execute naval fleet database synchronization."""
    settings = get_settings()
    with psycopg.connect(settings.psycopg_database_url) as conn:
        with conn.transaction():
            res = seed_naval_fleets(conn)
    return res
